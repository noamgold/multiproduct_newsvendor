def make_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--n-values", default="100")
    parser.add_argument("--replications", default="all")
    parser.add_argument("--solver", default=DEFAULT_SOLVER)
    parser.add_argument(
        "--methods", default=DEFAULT_METHODS,
        help=f"'all' or a comma-separated subset of {list(METHOD_CHOICES)}",
    )
    parser.add_argument("--time-limit", type=float, default=DEFAULT_TIME_LIMIT_SECONDS)
    parser.add_argument(
        "--mip-gap", type=float, default=DEFAULT_MIP_GAP,
        help="relative optimality gap applied to every method (default 5e-4 = 0.05%%)",
    )
    parser.add_argument("--threads", type=int, default=DEFAULT_THREADS)
    parser.add_argument("--instances-csv", default=DEFAULT_INSTANCES_CSV)
    parser.add_argument("--results-csv", default=DEFAULT_RESULTS_CSV)
    parser.add_argument(
        "--cut-family", choices=tsc.CUT_FAMILY_CHOICES, default=tsc.DEFAULT_CUT_FAMILY,
        help=(
            "which valid inequality the callback separates: 'dual' (one f-evaluation per cut, "
            "the capacity-price cut of Lemma 1) or 'nemhauser-wolsey' (inequality (6b) with "
            "exact marginals, O(n) f-evaluations per cut)"
        ),
    )
    # Back-compatible aliases for the old either/or flag, kept so existing
    # invocations keep working; both simply preselect --methods.
    parser.add_argument(
        "--submodular-cuts", dest="methods", action="store_const", const=CUTS_METHOD,
        help="deprecated alias for --methods cuts (solve only with the cut master)",
    )
    parser.add_argument(
        "--no-submodular-cuts", dest="methods", action="store_const",
        const=f"{BIGM_METHOD},{PERSPECTIVE_METHOD}",
        help="deprecated alias for --methods bigm,perspective (MISOCPs only)",
    )
    return parser


def summarize(rows: Sequence[dict[str, Any]], methods: Sequence[str]) -> None:
    """Print the per-n table: mean solve time and mean node count per
    method, plus how often the cut master's objective matched each MISOCP.
    """
    n_values = sorted({int(row["n"]) for row in rows})
    header = f"{'n':>6} {'reps':>5}"
    for method in methods:
        header += f" | {METHOD_LABELS[method]:>12} {'nodes':>9}"
    print("\n" + header)
    print("-" * len(header))
    for n in n_values:
        line = f"{n:>6}"
        reps = len({row["instance_id"] for row in rows if int(row["n"]) == n})
        line += f" {reps:>5}"
        for method in methods:
            selected = [row for row in rows if int(row["n"]) == n and row["method"] == method]
            times = [
                float(row["solve_seconds"]) for row in selected if row["solve_seconds"] is not None
            ]
            nodes = [float(row["node_count"]) for row in selected if row["node_count"] is not None]
            mean_time = statistics.fmean(times) if times else float("nan")
            mean_nodes = statistics.fmean(nodes) if nodes else float("nan")
            line += f" | {mean_time:>12.3f} {mean_nodes:>9.1f}"
        print(line)

    for left, right in COMPARISON_PAIRS:
        if left not in methods or right not in methods:
            continue
        column = f"{left}_vs_{right}_classification"
        counts: dict[str, int] = {}
        for row in rows:
            if row["method"] != left:
                continue
            counts[row[column]] = counts.get(row[column], 0) + 1
        summary = ", ".join(f"{key}={value}" for key, value in sorted(counts.items()))
        print(f"{METHOD_LABELS[left]:>12} vs {METHOD_LABELS[right]:<12}: {summary}")


def main(argv: Sequence[str] | None = None) -> int:
    args = make_parser().parse_args(argv)
    n_values = rte.parse_int_selection(args.n_values, rte.TABLE2_N_VALUES, "n")
    replications = rte.parse_int_selection(
        args.replications, rte.TABLE2_REPLICATIONS, "replication"
    )
    methods = parse_methods(args.methods)
    match_abs_tol, match_rel_tol = model_match_tolerances(args.mip_gap)

    base = Path(__file__).parent
    instances = gsc.read_selected_strongly_correlated_instances(
        base / args.instances_csv, n_values, replications
    )

    results_path = base / args.results_csv
    written_rows: list[dict[str, Any]] = []
    with results_path.open("w", encoding="utf-8", newline="") as out_stream:
        writer = csv.DictWriter(out_stream, fieldnames=RESULT_FIELDNAMES)
        writer.writeheader()
        for instance in instances:
            results_by_method: dict[str, dict[str, Any]] = {}
            for method in methods:
                if method == CUTS_METHOD:
                    result = solve_cuts_and_collect_stats(
                        instance,
                        time_limit_seconds=args.time_limit,
                        mip_gap=args.mip_gap,
                        threads=args.threads,
                        cut_family=args.cut_family,
                    )
                else:
                    result = solve_misocp_and_collect_stats(
                        instance,
                        METHOD_MODEL_IDS[method],
                        solver=args.solver,
                        time_limit_seconds=args.time_limit,
                        mip_gap=args.mip_gap,
                        threads=args.threads,
                    )
                results_by_method[method] = result
                print(
                    f"{instance.instance_id} {METHOD_LABELS[method]}: "
                    f"status={result['status']} nodes={result['node_count']} "
                    f"solve_s={result['solve_seconds']:.2f}"
                )

            comparisons = {
                f"{left}_vs_{right}": compare_methods(
                    results_by_method, left, right,
                    match_abs_tol=match_abs_tol, match_rel_tol=match_rel_tol,
                )
                for left, right in COMPARISON_PAIRS
            }
            best = best_independent_objective(results_by_method)

            for method, result in results_by_method.items():
                own = result["independent_objective"]
                shortfall = (
                    (best - own) / abs(best)
                    if best is not None and own is not None and best != 0.0
                    else None
                )
                row = {
                    "instance_id": instance.instance_id,
                    "n": instance.n,
                    "replication": instance.replication,
                    "method": method,
                    "model_id": METHOD_MODEL_IDS[method],
                    # The cut master always runs on GUROBI (lazy-constraint
                    # callback); --solver only selects the MISOCP backend.
                    "solver": "GUROBI" if method == CUTS_METHOD else args.solver,
                    "mip_gap_setting": args.mip_gap,
                    "status": result["status"],
                    "objective": result["objective"],
                    "independent_objective": own,
                    "node_count": result["node_count"],
                    "native_relative_gap": result["native_relative_gap"],
                    "solve_seconds": result["solve_seconds"],
                    "has_incumbent": result["has_incumbent"],
                    "soc_ok": result["soc_ok"],
                    "economic_abs_diff": result["economic_abs_diff"],
                    "cut_count": result["cut_count"],
                    "oracle_evaluations": result["oracle_evaluations"],
                    "best_independent_objective": best,
                    "shortfall_vs_best_rel": shortfall,
                }
                for pair, (absolute, relative, classification) in comparisons.items():
                    row[f"{pair}_abs_diff"] = absolute
                    row[f"{pair}_rel_diff"] = relative
                    row[f"{pair}_classification"] = classification
                writer.writerow(row)
                written_rows.append(row)
            out_stream.flush()

    print(f"\nWrote results to {results_path}")
    summarize(written_rows, methods)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
