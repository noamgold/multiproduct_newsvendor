"""Build a new Table 2 on the strongly-correlated fixed-cost TRIANGULAR
instances (generated by generate_strongly_correlated_instances.py), solving
each instance three ways and reporting them side by side:

  * Big-M (15)     -- rte.BIGM_MODEL_ID, the lifted big-M MISOCP (15a)-(15j),
                      GUROBI
  * Conic (11)     -- rte.PERSPECTIVE_MODEL_ID, shorthand for "(15) with the
                      hyperbolic constraint (15c) replaced by the bilinear
                      perspective constraint (11)", GUROBI
  * Conic+(15i)    -- rte.PERSPECTIVE_BOUNDED_MODEL_ID, that same perspective
                      MISOCP plus the valid inequality (15i),
                      u_hat_i <= (min{x^U_i, m_i} - a_i)^2. (15i) is stated
                      for the perspective formulation only, and
                      triangular_current refuses to build it with the big-M
                      lift.
  * Cuts           -- submodular_cuts.solve_triangular_fixed_cost_submodular_cuts:
                    a pure-binary knapsack master plus Nemhauser-Wolsey /
                    capacity-price cuts separated in a GUROBI lazy-constraint
                    callback. This REPLACES the MISOCP (the continuous
                    variables are projected out, Corollary 1); it is not an
                    MISOCP strengthened with cuts.

The cut method used to be an either/or alternative here, selected by
--submodular-cuts. It is now one of four methods that all run on every
instance by default, so the table carries every pairwise comparison
directly. (The old flags still work as aliases -- see make_parser.)
This mirrors run_uniform_strongly_correlated.py; the two scripts are kept
structurally identical so they can be diffed against each other.

Every method is given the SAME relative optimality gap, DEFAULT_MIP_GAP =
5e-4 (0.05 percent), so that objective differences between methods are
read against one common tolerance. (Earlier runs of this script used
1e-3, then 1e-4; 5e-4 is what the current Table 2 batch is specified at.)

Objectives are compared on independent_objective -- each method's own
order quantities q fed back through the closed-form Triangular
expected-profit function (7) (rte.recompute_triangular_expected_profit),
never the solver's self-reported value. That is the only basis on which a
lifted MISOCP and a projected cut master are comparable at all.

See generate_strongly_correlated_instances.py's module docstring for the
instance-set background: this variant rebuilds each product's fixed cost
with the minimal non-negativity-preserving shift (k_i =
fixed_cost_score_i + delta, delta as small as feasible) instead of the
manuscript's max(score)/10, pushing further along the same Pisinger
"strongly correlated knapsack" axis the manuscript itself already uses to
build hard instances.

This is an exploratory research probe, not an official logged Table 2 run:
it writes one flat CSV of per-(instance, method) results, and does not run
the full repair/validation machinery of run_triangular_table2_experiment.py
(though it does perform the same lightweight SOC/economic sanity check).

(This script previously also compared B&B node counts / solve times
against the manuscript's own (equation (13)) Table 2 GUROBI results for the
same n/replication/model, via load_baseline_stats(); that comparison is no
longer needed and has been commented out rather than deleted, in case it's
wanted again.)

Usage:

    python run_triangular_strongly_correlated.py --n-values 100 --replications 1-10
    python run_triangular_strongly_correlated.py --n-values all --replications all
"""

