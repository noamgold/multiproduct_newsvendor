def parse_methods(text: str) -> tuple[str, ...]:
    """Parse --methods: 'all' or a comma-separated subset of METHOD_CHOICES,
    always returned in METHOD_CHOICES order so the results file's row order
    is independent of how the flag was typed.
    """
    cleaned = text.strip().lower()
    if cleaned in {"all", "both"}:
        return METHOD_CHOICES
    requested = {item.strip() for item in cleaned.split(",") if item.strip()}
    unknown = sorted(requested - set(METHOD_CHOICES))
    rte.require(not unknown, f"unknown method(s): {unknown}; choose from {list(METHOD_CHOICES)}")
    rte.require(bool(requested), "--methods selected nothing")
    return tuple(method for method in METHOD_CHOICES if method in requested)


def solve_misocp_and_collect_stats(
    instance: rte.TriangularInstance,
    model_id: str,
    *,
    solver: str,
    time_limit_seconds: float,
    mip_gap: float,
    threads: int,
) -> dict[str, Any]:
    """Build, solve, and lightly sanity-check one (instance, MISOCP model)
    pair. Mirrors the core solve path of run_triangular_table2_experiment.py's
    solve_triangular_table2_formulation, but skips its full CSV/repair
    machinery since this is an exploratory probe, not an official logged
    Table 2 run.
    """
    bundle = rte.build_current_manuscript_triangular_model(instance, model_id)
    data, chain, inverse_data = bundle.problem.get_problem_data(solver=solver)
    solve_opts = tc.solver_options(
        solver, time_limit_seconds=time_limit_seconds, mip_gap=mip_gap, threads=threads
    )
    start = time.perf_counter()
    raw_solution = chain.solve_via_data(
        bundle.problem, data, warm_start=False, verbose=False, solver_opts=solve_opts
    )
    solve_seconds = time.perf_counter() - start
    native_stats = rte.extract_native_stats(raw_solution, solver)
    bundle.problem.unpack_results(raw_solution, chain, inverse_data)

    vector_names = ("bar_x", "hat_x", "y", "u_hat", "w_hat", "u_y", "w_y", "z")
    vectors = {
        name: rte.finite_vector(bundle.variables[name].value, instance.n) for name in vector_names
    }
    has_incumbent = all(vectors[name] is not None for name in vector_names)
    objective = (
        float(bundle.problem.value)
        if has_incumbent and bundle.problem.value is not None
        else None
    )

    soc_ok = None
    economic_abs_diff = None
    independent_objective = None
    if has_incumbent and objective is not None:
        tilde = [instance.b[i] - instance.m[i] - vectors["y"][i] for i in range(instance.n)]
        q = [vectors["bar_x"][i] + vectors["hat_x"][i] + tilde[i] for i in range(instance.n)]
        independent_objective = rte.recompute_triangular_expected_profit(instance, q)
        economic_abs_diff = abs(objective - independent_objective)
        multiplier = (
            (lambda i: 1.0) if model_id == rte.BIGM_MODEL_ID else (lambda i: vectors["z"][i])
        )
        max_violation = 0.0
        for i in range(instance.n):
            for lhs, rhs in (
                (vectors["hat_x"][i] ** 2, vectors["u_hat"][i] * multiplier(i)),
                (vectors["u_hat"][i] ** 2, vectors["w_hat"][i] * vectors["hat_x"][i]),
                (vectors["y"][i] ** 2, vectors["u_y"][i]),
                (vectors["u_y"][i] ** 2, vectors["w_y"][i] * vectors["y"][i]),
            ):
                max_violation = max(max_violation, lhs - rhs)
        soc_ok = max_violation <= 1.0e-3 + 1.0e-6 * max(1.0, abs(objective))

    return {
        "status": str(bundle.problem.status),
        "objective": objective,
        # The comparable objective: the solver-reported objective trusts
        # whatever the (possibly slightly SOC-infeasible) lift variables
        # say, whereas this is recomputed independently from the actual
        # physical order quantities q via the closed-form profit function
        # (7) -- the same quantity run_triangular_table2_experiment.py calls
        # objective_independent_common. This is what every cross-method
        # comparison below uses, and what run_triangular_cubic2018_minlp_
        # compare.py compares Bonmin's/SCIP's objective against.
        "independent_objective": independent_objective,
        "node_count": native_stats.get("node_count"),
        "native_relative_gap": native_stats.get("native_relative_gap"),
        "solve_seconds": solve_seconds,
        "has_incumbent": has_incumbent,
        "soc_ok": soc_ok,
        "economic_abs_diff": economic_abs_diff,
        "cut_count": None,
        "oracle_evaluations": None,
    }


def solve_cuts_and_collect_stats(
    instance: rte.TriangularInstance,
    *,
    time_limit_seconds: float,
    mip_gap: float,
    threads: int,
    cut_family: str,
) -> dict[str, Any]:
    """Solve one instance with the submodular-cut master and report it in
    the same shape solve_misocp_and_collect_stats returns.

    There is no Big-M/Perspective distinction here: those two differ only
    in how the cubic terms are lifted into cones, and this formulation
    projects the continuous variables out entirely (Corollary 1), leaving
    one model per instance. ``soc_ok`` is therefore None -- the master has
    no second-order cones to check -- and economic_abs_diff carries the
    meaningful validation instead: the gap between the master's reported
    optimum and the same closed-form profit recomputation (7) used for
    every other method, evaluated at the returned order quantities.
    """
    result = tsc.solve_triangular_fixed_cost_submodular_cuts(
        instance.a, instance.m, instance.b,
        instance.price_p, instance.cost_c, instance.salvage_s,
        instance.x_u, instance.k, instance.C, instance.K,
        time_limit_seconds=time_limit_seconds,
        mip_gap=mip_gap,
        threads=threads,
        cut_family=cut_family,
    )

    independent_objective = None
    economic_abs_diff = None
    if result.quantities is not None:
        independent_objective = rte.recompute_triangular_expected_profit(
            instance, result.quantities.tolist()
        )
        if result.objective is not None:
            economic_abs_diff = abs(result.objective - independent_objective)

    return {
        "status": result.status,
        "objective": result.objective,
        "independent_objective": independent_objective,
        "node_count": result.node_count,
        "native_relative_gap": result.mip_gap,
        "solve_seconds": result.solve_seconds,
        "has_incumbent": result.objective is not None,
        "soc_ok": None,
        "economic_abs_diff": economic_abs_diff,
        "cut_count": result.cut_count,
        "oracle_evaluations": result.oracle_evaluations,
    }


def compare_methods(
    results_by_method: dict[str, dict[str, Any]],
    left_method: str,
    right_method: str,
    *,
    match_abs_tol: float,
    match_rel_tol: float,
) -> tuple[float | None, float | None, str]:
    """Compare two methods' independent_objective on one instance, using
    the same tolerance machinery run_triangular_table2_experiment.py uses
    for its own bigm_vs_perspective comparison
    (triangular_table2_model_comparison.csv) -- scaled_tolerance, PASS iff
    the absolute difference is within the threshold -- but with the
    tolerances scaled to this script's tighter MIP gap, see
    model_match_tolerances().

    Unlike the old same-solver-only version of this function, the
    cuts-vs-MISOCP pairs it now also serves are genuinely cross-method:
    one side is a lifted MISOCP solved by --solver, the other a projected
    binary master with a cut callback.
    """
    left_result = results_by_method.get(left_method)
    right_result = results_by_method.get(right_method)
    if left_result is None or right_result is None:
        return None, None, "NOT_COMPARABLE_MISSING_METHOD"
    left = left_result["independent_objective"]
    right = right_result["independent_objective"]
    if left is None or right is None:
        return None, None, "NOT_COMPARABLE_DUE_TO_STATUS"
    absolute = abs(left - right)
    relative = rte.relative_difference(left, right)
    threshold = rte.scaled_tolerance(match_abs_tol, match_rel_tol, left, right)
    classification = "PASS" if absolute <= threshold else "FAIL"
    return absolute, relative, classification


def model_match_tolerances(mip_gap: float) -> tuple[float, float]:
    """Objective-agreement tolerances for the cross-method comparisons.

    run_triangular_table2_experiment.py documents its own
    DEFAULT_MODEL_MATCH_REL_TOL (0.002) as "twice default MIP gap" (its
    default gap being 1e-3). That relationship is what makes the test
    meaningful -- two methods each stopping within `gap` of the optimum can
    legitimately differ by up to about 2*gap -- so it is preserved here
    rather than the constant, which would otherwise be 20x looser than this
    script's tighter gap warrants.
    """
    return rte.DEFAULT_MODEL_MATCH_ABS_TOL, 2.0 * mip_gap


def best_independent_objective(results_by_method: dict[str, dict[str, Any]]) -> float | None:
    values = [
        result["independent_objective"]
        for result in results_by_method.values()
        if result["independent_objective"] is not None
    ]
    return max(values) if values else None


