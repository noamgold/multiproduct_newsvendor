"""Build a new Table 1 on the strongly-correlated fixed-cost UNIFORM
instances (generated by generate_uniform_strongly_correlated_instances.py),
solving each instance three ways and reporting them side by side:

  * Big-M (4)    -- rue.BIGM_MODEL_ID, the lifted MISOCP, GUROBI
  * Conic (6)    -- rue.PERSPECTIVE_MODEL_ID, the perspective MISOCP, GUROBI
  * Cuts         -- submodular_cuts.solve_uniform_fixed_cost_submodular_cuts:
                    a pure-binary knapsack master plus Nemhauser-Wolsey /
                    capacity-price cuts separated in a GUROBI lazy-constraint
                    callback. This REPLACES the MISOCP (the continuous
                    variables are projected out, Corollary 1); it is not an
                    MISOCP strengthened with cuts.

This differs from run_triangular_strongly_correlated.py, where the cut
method is an either/or alternative selected by a flag: here all three
methods run on every instance by default so the new table can carry the
cuts-vs-MISOCP comparison columns directly.

Every method is given the SAME relative optimality gap, DEFAULT_MIP_GAP =
5e-4 (0.05 percent), tighter than the 1e-3 used in earlier runs, so that
objective differences between methods are read against one common
tolerance.

Objectives are compared on independent_objective -- each method's own
order quantities q fed back through the closed-form Uniform expected-profit
function (rue.recompute_uniform_expected_profit), never the solver's
self-reported value. That is the only basis on which a lifted MISOCP and a
projected cut master are comparable at all.

Usage:

    python run_uniform_strongly_correlated.py --n-values 100 --replications 1-10
    python run_uniform_strongly_correlated.py --n-values all --replications all
"""

from __future__ import annotations

import argparse
import csv
import statistics
import time
from pathlib import Path
from typing import Any, Iterable, Sequence

import generate_uniform_strongly_correlated_instances as gscu
import run_uniform_table1_experiment as rue
import submodular_cuts as tsc
import triangular_current as tc

DEFAULT_INSTANCES_CSV = "uniform_table1_instances_strongly_correlated.csv"
DEFAULT_RESULTS_CSV = "strongly_correlated_table1_results.csv"

# 0.05 percent for every method (MISOCP and cut master alike). Earlier
# Table 1/Table 2 runs used 1e-3; the tighter setting here is what the new
# table is specified at.
DEFAULT_MIP_GAP = 5.0e-4
DEFAULT_TIME_LIMIT_SECONDS = 3600.0
DEFAULT_THREADS = 1
DEFAULT_SOLVER = "GUROBI"
DEFAULT_METHODS = "all"

BIGM_METHOD = "bigm"
PERSPECTIVE_METHOD = "perspective"
CUTS_METHOD = "cuts"
NOT_APPLICABLE_CUT_FAMILY = "NOT_APPLICABLE"
METHOD_CHOICES = (BIGM_METHOD, PERSPECTIVE_METHOD, CUTS_METHOD)
METHOD_MODEL_IDS = {
    BIGM_METHOD: rue.BIGM_MODEL_ID,
    PERSPECTIVE_METHOD: rue.PERSPECTIVE_MODEL_ID,
    CUTS_METHOD: tsc.UNIFORM_MODEL_ID,
}
METHOD_LABELS = {
    BIGM_METHOD: "Big-M (4)",
    PERSPECTIVE_METHOD: "Conic (6)",
    CUTS_METHOD: "Cuts",
}

RESULT_FIELDNAMES = (
    "instance_id", "n", "replication", "method", "cut_family", "model_id", "solver",
    "mip_gap_setting",
    "status", "objective", "independent_objective",
    "node_count", "native_relative_gap", "solve_seconds",
    "has_incumbent", "soc_ok", "economic_abs_diff",
    "cut_count", "oracle_evaluations",
    "best_independent_objective", "shortfall_vs_best_rel",
    "bigm_vs_perspective_abs_diff", "bigm_vs_perspective_rel_diff",
    "bigm_vs_perspective_classification",
    "cuts_vs_bigm_abs_diff", "cuts_vs_bigm_rel_diff",
    "cuts_vs_bigm_classification",
    "cuts_vs_perspective_abs_diff", "cuts_vs_perspective_rel_diff",
    "cuts_vs_perspective_classification",
)


def parse_methods(text: str) -> tuple[str, ...]:
    """Parse --methods: 'all' or a comma-separated subset of METHOD_CHOICES,
    always returned in METHOD_CHOICES order so the results file's row order
    is independent of how the flag was typed.
    """
    cleaned = text.strip().lower()
    if cleaned in {"all", "both"}:
        return METHOD_CHOICES
    requested = {item.strip() for item in cleaned.split(",") if item.strip()}
    unknown = sorted(requested - set(METHOD_CHOICES))
    rue.require(not unknown, f"unknown method(s): {unknown}; choose from {list(METHOD_CHOICES)}")
    rue.require(bool(requested), "--methods selected nothing")
    return tuple(method for method in METHOD_CHOICES if method in requested)


def solve_misocp_and_collect_stats(
    instance: rue.UniformInstance,
    model_id: str,
    *,
    solver: str,
    time_limit_seconds: float,
    mip_gap: float,
    threads: int,
) -> dict[str, Any]:
    """Build, solve, and lightly sanity-check one (instance, MISOCP model)
    pair. Mirrors run_triangular_strongly_correlated.solve_and_collect_stats,
    adapted to the Uniform lift, which has a single rotated cone per product
    (hat_x^2 <= u * multiplier) rather than the triangular cube tower.
    """
    bundle = rue.build_current_manuscript_uniform_model(instance, model_id)
    data, chain, inverse_data = bundle.problem.get_problem_data(solver=solver)
    solve_opts = tc.solver_options(
        solver, time_limit_seconds=time_limit_seconds, mip_gap=mip_gap, threads=threads
    )
    start = time.perf_counter()
    raw_solution = chain.solve_via_data(
        bundle.problem, data, warm_start=False, verbose=False, solver_opts=solve_opts
    )
    solve_seconds = time.perf_counter() - start
    native_stats = rue.extract_native_stats(raw_solution, solver)
    bundle.problem.unpack_results(raw_solution, chain, inverse_data)

    vector_names = ("bar_x", "hat_x", "u", "z")
    vectors = {
        name: rue.finite_vector(bundle.variables[name].value, instance.n) for name in vector_names
    }
    has_incumbent = all(vectors[name] is not None for name in vector_names)
    objective = (
        float(bundle.problem.value)
        if has_incumbent and bundle.problem.value is not None
        else None
    )

    soc_ok = None
    economic_abs_diff = None
    independent_objective = None
    if has_incumbent and objective is not None:
        q = [vectors["bar_x"][i] + vectors["hat_x"][i] for i in range(instance.n)]
        independent_objective = rue.recompute_uniform_expected_profit(instance, q)
        economic_abs_diff = abs(objective - independent_objective)
        multiplier = (
            (lambda i: 1.0) if model_id == rue.BIGM_MODEL_ID else (lambda i: vectors["z"][i])
        )
        max_violation = max(
            vectors["hat_x"][i] ** 2 - vectors["u"][i] * multiplier(i)
            for i in range(instance.n)
        )
        soc_ok = max_violation <= 1.0e-3 + 1.0e-6 * max(1.0, abs(objective))

    return {
        "status": str(bundle.problem.status),
        "objective": objective,
        # The comparable objective: recomputed from the physical order
        # quantities q through the closed-form Uniform profit function,
        # rather than trusting the (possibly slightly cone-infeasible) lift
        # variables. This is what every cross-method comparison below uses.
        "independent_objective": independent_objective,
        "node_count": native_stats.get("node_count"),
        "native_relative_gap": native_stats.get("native_relative_gap"),
        "solve_seconds": solve_seconds,
        "has_incumbent": has_incumbent,
        "soc_ok": soc_ok,
        "economic_abs_diff": economic_abs_diff,
        "cut_count": None,
        "oracle_evaluations": None,
    }


def solve_cuts_and_collect_stats(
    instance: rue.UniformInstance,
    *,
    time_limit_seconds: float,
    mip_gap: float,
    threads: int,
    cut_family: str,
) -> dict[str, Any]:
    """Solve one instance with the submodular-cut master and report it in
    the same shape solve_misocp_and_collect_stats returns.

    ``soc_ok`` is None: the master has no second-order cones to check. The
    meaningful validation is economic_abs_diff -- the gap between the
    master's reported optimum and the same closed-form profit recomputation
    used for the MISOCPs, evaluated at the returned order quantities.
    """
    result = tsc.solve_uniform_fixed_cost_submodular_cuts(
        instance.a, instance.b,
        instance.price_p, instance.cost_c, instance.salvage_s,
        instance.x_u, instance.k, instance.C, instance.K,
        time_limit_seconds=time_limit_seconds,
        mip_gap=mip_gap,
        threads=threads,
        cut_family=cut_family,
    )

    independent_objective = None
    economic_abs_diff = None
    if result.quantities is not None:
        independent_objective = rue.recompute_uniform_expected_profit(
            instance, result.quantities.tolist()
        )
        if result.objective is not None:
            economic_abs_diff = abs(result.objective - independent_objective)

    return {
        "status": result.status,
        "objective": result.objective,
        "independent_objective": independent_objective,
        "node_count": result.node_count,
        "native_relative_gap": result.mip_gap,
        "solve_seconds": result.solve_seconds,
        "has_incumbent": result.objective is not None,
        "soc_ok": None,
        "economic_abs_diff": economic_abs_diff,
        "cut_count": result.cut_count,
        "oracle_evaluations": result.oracle_evaluations,
    }


def compare_methods(
    results_by_method: dict[str, dict[str, Any]],
    left_method: str,
    right_method: str,
    *,
    match_abs_tol: float,
    match_rel_tol: float,
) -> tuple[float | None, float | None, str]:
    """Compare two methods' independent_objective on one instance, using
    the same tolerance machinery run_uniform_table1_experiment.py uses for
    its own model comparison (scaled_tolerance; PASS iff the absolute
    difference is within the threshold), but with the tolerances scaled to
    this script's tighter MIP gap -- see model_match_tolerances().
    """
    left_result = results_by_method.get(left_method)
    right_result = results_by_method.get(right_method)
    if left_result is None or right_result is None:
        return None, None, "NOT_COMPARABLE_MISSING_METHOD"
    left = left_result["independent_objective"]
    right = right_result["independent_objective"]
    if left is None or right is None:
        return None, None, "NOT_COMPARABLE_DUE_TO_STATUS"
    absolute = abs(left - right)
    relative = rue.relative_difference(left, right)
    threshold = rue.scaled_tolerance(match_abs_tol, match_rel_tol, left, right)
    classification = "PASS" if absolute <= threshold else "FAIL"
    return absolute, relative, classification


def model_match_tolerances(mip_gap: float) -> tuple[float, float]:
    """Objective-agreement tolerances for the cross-method comparisons.

    run_uniform_table1_experiment.py documents its own
    DEFAULT_MODEL_MATCH_REL_TOL (0.001) as "twice default MIP gap" (its
    default gap being 1e-3). That relationship is what makes the test
    meaningful -- two methods each stopping within `gap` of the optimum can
    legitimately differ by up to about 2*gap -- so it is preserved here
    rather than the constant, which would otherwise be 20x looser than this
    script's tighter gap warrants.
    """
    return rue.DEFAULT_MODEL_MATCH_ABS_TOL, 2.0 * mip_gap


def best_independent_objective(results_by_method: dict[str, dict[str, Any]]) -> float | None:
    values = [
        result["independent_objective"]
        for result in results_by_method.values()
        if result["independent_objective"] is not None
    ]
    return max(values) if values else None


def make_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--n-values", default="100")
    parser.add_argument("--replications", default="all")
    parser.add_argument("--solver", default=DEFAULT_SOLVER)
    parser.add_argument(
        "--methods", default=DEFAULT_METHODS,
        help=f"'all' or a comma-separated subset of {list(METHOD_CHOICES)}",
    )
    parser.add_argument("--time-limit", type=float, default=DEFAULT_TIME_LIMIT_SECONDS)
    parser.add_argument(
        "--mip-gap", type=float, default=DEFAULT_MIP_GAP,
        help="relative optimality gap applied to every method (default 5e-4 = 0.05%%)",
    )
    parser.add_argument("--threads", type=int, default=DEFAULT_THREADS)
    parser.add_argument("--instances-csv", default=DEFAULT_INSTANCES_CSV)
    parser.add_argument("--results-csv", default=DEFAULT_RESULTS_CSV)
    parser.add_argument(
        "--cut-family", choices=tsc.CUT_FAMILY_CHOICES, default=tsc.DEFAULT_CUT_FAMILY,
        help=(
            "which valid inequality the callback separates: 'dual' (one f-evaluation per cut, "
            "the capacity-price cut of Lemma 1) or 'nemhauser-wolsey' (exact inequality (8b) with "
            "exact marginals, O(n) f-evaluations per cut)"
        ),
    )
    parser.add_argument(
        "--resume", action="store_true",
        help="append only missing (instance, method, cut-family) rows to a compatible CSV",
    )
    return parser


def summarize(rows: Sequence[dict[str, Any]], methods: Sequence[str]) -> None:
    """Print the per-n table: mean solve time and mean node count per
    method, plus how often the cut master's objective matched each MISOCP.
    """
    n_values = sorted({int(row["n"]) for row in rows})
    header = f"{'n':>6} {'reps':>5}"
    for method in methods:
        header += f" | {METHOD_LABELS[method]:>12} {'nodes':>9}"
    print("\n" + header)
    print("-" * len(header))
    for n in n_values:
        line = f"{n:>6}"
        reps = len({row["instance_id"] for row in rows if int(row["n"]) == n})
        line += f" {reps:>5}"
        for method in methods:
            selected = [
                row for row in rows if int(row["n"]) == n and row["method"] == method
            ]
            times = [float(row["solve_seconds"]) for row in selected if row["solve_seconds"] is not None]
            nodes = [
                float(row["node_count"]) for row in selected if row["node_count"] is not None
            ]
            mean_time = statistics.fmean(times) if times else float("nan")
            mean_nodes = statistics.fmean(nodes) if nodes else float("nan")
            line += f" | {mean_time:>12.3f} {mean_nodes:>9.1f}"
        print(line)

    for left, right in ((CUTS_METHOD, BIGM_METHOD), (CUTS_METHOD, PERSPECTIVE_METHOD)):
        if left not in methods or right not in methods:
            continue
        column = f"{left}_vs_{right}_classification"
        counts: dict[str, int] = {}
        for row in rows:
            if row["method"] != left:
                continue
            counts[row[column]] = counts.get(row[column], 0) + 1
        summary = ", ".join(f"{key}={value}" for key, value in sorted(counts.items()))
        print(f"{METHOD_LABELS[left]} vs {METHOD_LABELS[right]}: {summary}")


def main(argv: Sequence[str] | None = None) -> int:
    args = make_parser().parse_args(argv)
    n_values = rue.parse_int_selection(args.n_values, rue.TABLE1_N_VALUES, "n")
    replications = rue.parse_int_selection(
        args.replications, rue.TABLE1_REPLICATIONS, "replication"
    )
    methods = parse_methods(args.methods)
    match_abs_tol, match_rel_tol = model_match_tolerances(args.mip_gap)

    base = Path(__file__).parent
    instances = gscu.read_selected_strongly_correlated_uniform_instances(
        base / args.instances_csv, n_values, replications
    )

    results_path = base / args.results_csv
    completed_keys: set[tuple[str, str, str]] = set()
    append_existing = args.resume and results_path.exists() and results_path.stat().st_size > 0
    if append_existing:
        with results_path.open("r", encoding="utf-8-sig", newline="") as existing_stream:
            existing_reader = csv.DictReader(existing_stream)
            rue.require(
                tuple(existing_reader.fieldnames or ()) == RESULT_FIELDNAMES,
                f"{results_path} has an incompatible CSV schema; refusing to resume",
            )
            for row in existing_reader:
                completed_keys.add((row["instance_id"], row["method"], row["cut_family"]))

    written_rows: list[dict[str, Any]] = []
    mode = "a" if append_existing else "w"
    with results_path.open(mode, encoding="utf-8", newline="") as out_stream:
        writer = csv.DictWriter(out_stream, fieldnames=RESULT_FIELDNAMES)
        if mode == "w":
            writer.writeheader()
            out_stream.flush()
        for instance in instances:
            results_by_method: dict[str, dict[str, Any]] = {}
            for method in methods:
                row_cut_family = args.cut_family if method == CUTS_METHOD else NOT_APPLICABLE_CUT_FAMILY
                key = (instance.instance_id, method, row_cut_family)
                if key in completed_keys:
                    print(
                        f"{instance.instance_id} {METHOD_LABELS[method]} "
                        f"[{row_cut_family}]: already present; skipped"
                    )
                    continue
                if method == CUTS_METHOD:
                    result = solve_cuts_and_collect_stats(
                        instance,
                        time_limit_seconds=args.time_limit,
                        mip_gap=args.mip_gap,
                        threads=args.threads,
                        cut_family=args.cut_family,
                    )
                else:
                    result = solve_misocp_and_collect_stats(
                        instance,
                        METHOD_MODEL_IDS[method],
                        solver=args.solver,
                        time_limit_seconds=args.time_limit,
                        mip_gap=args.mip_gap,
                        threads=args.threads,
                    )
                results_by_method[method] = result
                print(
                    f"{instance.instance_id} {METHOD_LABELS[method]}: "
                    f"status={result['status']} nodes={result['node_count']} "
                    f"solve_s={result['solve_seconds']:.2f}"
                )

            comparisons = {
                f"{left}_vs_{right}": compare_methods(
                    results_by_method, left, right,
                    match_abs_tol=match_abs_tol, match_rel_tol=match_rel_tol,
                )
                for left, right in (
                    (BIGM_METHOD, PERSPECTIVE_METHOD),
                    (CUTS_METHOD, BIGM_METHOD),
                    (CUTS_METHOD, PERSPECTIVE_METHOD),
                )
            }
            best = best_independent_objective(results_by_method)

            for method, result in results_by_method.items():
                own = result["independent_objective"]
                shortfall = (
                    (best - own) / abs(best)
                    if best is not None and own is not None and best != 0.0
                    else None
                )
                row = {
                    "instance_id": instance.instance_id,
                    "n": instance.n,
                    "replication": instance.replication,
                    "method": method,
                    "cut_family": (
                        args.cut_family if method == CUTS_METHOD else NOT_APPLICABLE_CUT_FAMILY
                    ),
                    "model_id": METHOD_MODEL_IDS[method],
                    # The cut master always runs on GUROBI (lazy-constraint
                    # callback); --solver only selects the MISOCP backend.
                    "solver": "GUROBI" if method == CUTS_METHOD else args.solver,
                    "mip_gap_setting": args.mip_gap,
                    "status": result["status"],
                    "objective": result["objective"],
                    "independent_objective": own,
                    "node_count": result["node_count"],
                    "native_relative_gap": result["native_relative_gap"],
                    "solve_seconds": result["solve_seconds"],
                    "has_incumbent": result["has_incumbent"],
                    "soc_ok": result["soc_ok"],
                    "economic_abs_diff": result["economic_abs_diff"],
                    "cut_count": result["cut_count"],
                    "oracle_evaluations": result["oracle_evaluations"],
                    "best_independent_objective": best,
                    "shortfall_vs_best_rel": shortfall,
                }
                for pair, (absolute, relative, classification) in comparisons.items():
                    row[f"{pair}_abs_diff"] = absolute
                    row[f"{pair}_rel_diff"] = relative
                    row[f"{pair}_classification"] = classification
                writer.writerow(row)
                out_stream.flush()
                written_rows.append(row)
                completed_keys.add(
                    (row["instance_id"], row["method"], row["cut_family"])
                )

    print(f"\nWrote results to {results_path}")
    summarize(written_rows, methods)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
