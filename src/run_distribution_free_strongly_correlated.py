"""Build a new Table 3 on the strongly-correlated fixed-cost
DISTRIBUTION-FREE instances (generated by
generate_strongly_correlated_distribution_free_instances.py), solving
each instance three ways and reporting them side by side:

  * Big-M (11)   -- dft.BIGM_MODEL_ID, the lifted MISOCP, GUROBI
  * Conic (12)   -- dft.PERSPECTIVE_MODEL_ID, the perspective MISOCP, GUROBI
  * Cuts         -- submodular_cuts.solve_distribution_free_fixed_cost_submodular_cuts:
                    a pure-binary knapsack master plus Nemhauser-Wolsey /
                    capacity-price cuts separated in a GUROBI lazy-constraint
                    callback. This REPLACES the MISOCP (the continuous
                    variables are projected out, Corollary 1); it is not an
                    MISOCP strengthened with cuts.

Every method is given the SAME relative optimality gap, DEFAULT_MIP_GAP =
1e-4 (0.01 percent), matching run_triangular_strongly_correlated.py and
run_uniform_strongly_correlated.py. This is the Table 3 member of that
family of scripts and is kept structurally identical to them, with one
genuine difference that the rest of this docstring is about.

COST SCALE vs. PROFIT SCALE -- read before interpreting the objectives
----------------------------------------------------------------------
Unlike Tables 1 and 2, the manuscript's Table 3 formulations (11)/(12)
MINIMIZE a cost, sum_i g_i(x_i), and a product left unstocked still costs
g_i(0) > 0 (the worst-case shortfall of not having it). The submodular
machinery instead maximizes the profit form pi_i(x) = g_i(0) - g_i(x),
which is what satisfies Assumption 1. The two are the same optimization
problem offset by the constant sum_i g_i(0):

    sum_i g_i(x_i) = zero_quantity_cost(instance) - sum_i pi_i(x_i)

On these instances that constant is roughly 3-5x the profit that the
decisions actually move, so a RELATIVE gap means something materially
weaker on the cost scale than on the profit scale. Consequences, all of
which this script makes explicit rather than hiding:

  * Each row records both scales: ``independent_objective`` is always the
    cost (11a)/(12) report, ``independent_profit`` always the profit.
    Both are recomputed from the method's own order quantities, never
    taken from the solver.
  * ``gap_scale`` says which scale that row's ``mip_gap_setting`` and
    ``native_relative_gap`` refer to: "cost" for the two MISOCPs, whose
    objective is the cost, and "profit" for the cut master, whose
    objective is the profit. The cut master is therefore held to a
    STRICTER absolute standard than the MISOCPs at the same nominal gap.
  * The PASS/FAIL comparisons are made on the COST scale, with tolerance
    2 x mip_gap -- i.e. against what the MISOCPs were actually asked to
    deliver, the looser of the two standards. A FAIL therefore means the
    difference exceeds what either method's own stated tolerance can
    excuse. The ``*_profit_rel_diff`` columns carry the same difference
    on the profit scale, which is the economically meaningful magnitude.

Because (11)/(12) minimize, LOWER ``independent_objective`` is better:
``best_independent_objective`` is the minimum over the methods and
``shortfall_vs_best_rel`` = (own - best) / |best| >= 0.

Usage:

    python run_distribution_free_strongly_correlated.py --n-values 100 --replications 1-10
    python run_distribution_free_strongly_correlated.py --n-values all --replications all
"""

